export type DiscoveredVideoBundle = {
  metaPath: string;
  compositionPath: string;
  source: "videos" | "examples";
};

export function discoverVideoMetaFiles(
  rootDir: string,
  source: "videos" | "examples" = "videos",
): DiscoveredVideoBundle[] {
  const abs = path.resolve(rootDir);
  if (!fs.existsSync(abs)) return [];
  const found: DiscoveredVideoBundle[] = [];

  const walk = (dir: string) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
        walk(full);
      } else if (entry.isFile() && entry.name === "meta.ts") {
        const compPath = path.join(dir, "composition.tsx");
        if (fs.existsSync(compPath)) {
          found.push({ metaPath: full, compositionPath: compPath, source });
        }
      }
    }
  };

  walk(abs);
  return found;
}

export type LoadedVideoDefinition = {
  metaPath: string;
  compositionPath: string;
  source: "videos" | "examples";
  definition: ResolvedVideoSpec;
};

export async function loadVideoDefinitions(
  roots?: ReadonlyArray<string | { dir: string; source: "videos" | "examples" }>,
): Promise<LoadedVideoDefinition[]> {
  const targetRoots: Array<{ dir: string; source: "videos" | "examples" }> =
    roots && roots.length > 0
      ? roots.map((r) =>
          typeof r === "string"
            ? { dir: r, source: r.includes("examples") ? "examples" : "videos" }
            : r,
        )
      : [
          { dir: DEFAULT_VIDEOS_ROOT, source: "videos" },
          { dir: DEFAULT_EXAMPLES_ROOT, source: "examples" },
        ];

  const loaded: LoadedVideoDefinition[] = [];
  for (const root of targetRoots) {
    for (const item of discoverVideoMetaFiles(root.dir, root.source)) {
      const mod = (await import(pathToFileURL(item.metaPath).href)) as {
        default?: ResolvedVideoSpec;
        video?: ResolvedVideoSpec;
      };
      const def = mod.default ?? mod.video;
      if (def && def.id && def.slug && def.category) {
        loaded.push({
          metaPath: item.metaPath,
          compositionPath: item.compositionPath,
          source: item.source,
          definition: def,
        });
      }
    }
  }
  return loaded;
}

export function findDuplicateCompositionIds(
  defs: ReadonlyArray<Pick<LoadedVideoDefinition, "definition" | "metaPath">>,
): Array<{ id: string; locations: string[] }> {
  const byId = new Map<string, string[]>();
  for (const item of defs) {
    const def = item.definition;
    const ids: string[] = [];
    if (def.registerBaseComposition) ids.push(def.id);
    for (const v of def.variants) ids.push(v.compositionId);

    for (const id of ids) {
      const list = byId.get(id) ?? [];
      list.push(`${def.category}/${def.collection}/${def.slug}`);
      byId.set(id, list);
    }
  }
  const dups: Array<{ id: string; locations: string[] }> = [];
  for (const [id, locations] of byId.entries()) {
    if (locations.length > 1) dups.push({ id, locations });
  }
  return dups;
}

export function syncRegistryFile(opts?: {
  registryPath?: string;
  videosRoot?: string;
  examplesRoot?: string;
}): { registryPath: string; count: number; entries: DiscoveredVideoBundle[] } {
  const registryPath = path.resolve(opts?.registryPath ?? REGISTRY_FILE_PATH);
  const videosRoot = path.resolve(opts?.videosRoot ?? DEFAULT_VIDEOS_ROOT);
  const examplesRoot = path.resolve(opts?.examplesRoot ?? DEFAULT_EXAMPLES_ROOT);

  const entries = [
    ...discoverVideoMetaFiles(videosRoot, "videos"),
    ...discoverVideoMetaFiles(examplesRoot, "examples"),
  ];

  const regDir = path.dirname(registryPath);
  const toRel = (absPath: string) => {
    let rel = path.relative(regDir, absPath).split(path.sep).join("/");
    if (!rel.startsWith(".")) rel = `./${rel}`;
    return rel;
  };

  const lines: string[] = [
    "// AUTO-GENERATED by `npm run video:sync` (do not edit manually).",
    'import type { ComponentType } from "react";',
    'import type { ResolvedVideoSpec } from "./core/contracts.ts";',
    "",
  ];

  entries.forEach((entry, idx) => {
    lines.push(`import meta_${idx} from ${JSON.stringify(toRel(entry.metaPath))};`);
    lines.push(`import * as comp_${idx} from ${JSON.stringify(toRel(entry.compositionPath))};`);
  });

  lines.push("");
  lines.push("export type RegisteredVideoEntry = {");
  lines.push('  source: "videos" | "examples";');
  lines.push("  definition: ResolvedVideoSpec<Record<string, unknown>>;");
  lines.push("  component: ComponentType<Record<string, unknown>>;");
  lines.push("  schema?: unknown;");
  lines.push("};");
  lines.push("");
  lines.push("export const REGISTERED_VIDEOS: readonly RegisteredVideoEntry[] = [");

  entries.forEach((entry, idx) => {
    lines.push("  {");
    lines.push(`    source: ${JSON.stringify(entry.source)},`);
    lines.push(`    definition: meta_${idx} as unknown as ResolvedVideoSpec<Record<string, unknown>>,`);
    lines.push(
      `    component: ((comp_${idx} as { default?: unknown }).default ?? Object.values(comp_${idx}).find((v) => typeof v === "function")) as ComponentType<Record<string, unknown>>,`,
    );
    lines.push(
      `    schema: "schema" in comp_${idx} ? (comp_${idx} as { schema?: unknown }).schema : undefined,`,
    );
    lines.push("  },");
  });

  lines.push("];");
  lines.push("");

  fs.mkdirSync(regDir, { recursive: true });
  fs.writeFileSync(registryPath, lines.join("\n"), "utf8");
  return { registryPath, count: entries.length, entries };
}

function titleFromSlug(slug: string): string {
  return slug
    .split("-")
    .map((w) => (w ? w[0]!.toUpperCase() + w.slice(1) : ""))
    .join(" ");
}

export function scaffoldVideoBundle(opts: {
  videosRoot?: string;
  registryPath?: string;
  examplesRoot?: string;
  sync?: boolean;
  category: VideoCategory;
  collection?: string;
  slug: string;
  id?: string;
  title?: string;
  description?: string;
  format?: VideoFormatPreset;
  fps?: number;
  durationSec?: number;
  durationInFrames?: number;
}): {
  dir: string;
  metaPath: string;
  compositionPath: string;
  id: string;
  collection: string;
  slug: string;
} {
  const root = path.resolve(opts.videosRoot ?? DEFAULT_VIDEOS_ROOT);
  const categoryDir = CATEGORY_DIR_MAP[opts.category];
  const collection = slugify(opts.collection || "default");
  const slug = slugify(opts.slug);
  const id = opts.id ?? pascalIdFromSlug(slug);
  const title = opts.title ?? titleFromSlug(slug);
  const description = opts.description ?? `${title} — composição ${opts.category} AnimesIce.`;
  const format: VideoFormatPreset =
    opts.format ??
    (opts.category === "GACHA"
      ? "GACHA_SQUARE"
      : opts.category === "PROMO"
        ? "PROMO_720P"
        : opts.category === "SHOWCASE"
          ? "CARD_PORTRAIT"
          : "SOCIAL_1_1");
  const fps = opts.fps ?? 30;
  const durationInFrames =
    opts.durationInFrames ?? Math.max(1, Math.round((opts.durationSec ?? 4) * fps));

  const dir = path.join(root, categoryDir, collection, slug);
  const metaPath = path.join(dir, "meta.ts");
  const compositionPath = path.join(dir, "composition.tsx");
  if (fs.existsSync(metaPath) || fs.existsSync(compositionPath)) {
    throw new Error(`Video bundle already exists: ${dir}`);
  }

  const srcImport = "../../../../src/shared.ts";
  const reactImport = "../../../../src/react.ts";
  const propTypeName = `${id}Props`;

  const metaContent = `import { defineVideo } from "${srcImport}";

export type ${propTypeName} = {
  title: string;
  subtitle: string;
  accentColor: string;
};

export const video = defineVideo<${propTypeName}>({
  id: ${JSON.stringify(id)},
  category: ${JSON.stringify(opts.category)},
  collection: ${JSON.stringify(collection)},
  slug: ${JSON.stringify(slug)},
  title: ${JSON.stringify(title)},
  description: ${JSON.stringify(description)},
  format: ${JSON.stringify(format)},
  fps: ${fps},
  durationInFrames: ${durationInFrames},
  codecProfile: "web-h264",
  tags: [${JSON.stringify(collection)}, ${JSON.stringify(opts.category.toLowerCase())}],
  defaultProps: {
    title: ${JSON.stringify(title)},
    subtitle: "AnimesIce Motion Studio",
    accentColor: "#38E8DA",
  },
});

export default video;
`;

  const compBody =
    opts.category === "GACHA"
      ? `      <Backdrop baseColor={ANIMESICE_PALETTE.inkDeep} glowColor={accentColor} glowOpacity={0.28} />
      <CrystalGeometry rarity="COMUM" pulse={pulse} />
      <EnergyRings colorA={accentColor} opacityPulse={pulse} />
      <Starfield count={28} color={accentColor} seed="${slug}" />
      <FoilSweep color={accentColor} startFrame={Math.round(durationInFrames * 0.22)} endFrame={Math.round(durationInFrames * 0.68)} />`
      : `      <Backdrop baseColor={ANIMESICE_PALETTE.inkDeep} glowColor={accentColor} showGrid />
      <Starfield count={36} color={accentColor} mode="twinkle" seed="${slug}" />
      <div
        style={{
          position: "relative",
          zIndex: 1,
          width: "100%",
          height: "100%",
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          padding: 48,
        }}
      >
        <TitleCard eyebrow="AnimesIce Studio" title={title} subtitle={subtitle} accentColor={accentColor} />
      </div>
      <FoilSweep color={accentColor} startFrame={Math.round(durationInFrames * 0.2)} endFrame={Math.round(durationInFrames * 0.65)} />`;

  const compContent = `import { useCurrentFrame, useVideoConfig } from "remotion";
import { z } from "zod";
import {
  ANIMESICE_PALETTE,
  Backdrop,
  CrystalGeometry,
  EnergyRings,
  FoilSweep,
  Stage,
  Starfield,
  TitleCard,
  loopProgress,
  pulseWave,
} from "${reactImport}";
import type { ${propTypeName} } from "./meta.ts";

export const schema = z.object({
  title: z.string(),
  subtitle: z.string(),
  accentColor: z.string(),
});

export default function ${id}Composition({
  title,
  subtitle,
  accentColor,
}: ${propTypeName}) {
  const frame = useCurrentFrame();
  const { durationInFrames } = useVideoConfig();
  const pulse = pulseWave(loopProgress(frame, durationInFrames), 3, 0.65, 0.14);

  return (
    <Stage background={ANIMESICE_PALETTE.inkDeep} format=${JSON.stringify(format)}>
${compBody}
    </Stage>
  );
}
`;

  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(metaPath, metaContent, "utf8");
  fs.writeFileSync(compositionPath, compContent, "utf8");

  if (opts.sync !== false) {
    syncRegistryFile({
      registryPath: opts.registryPath ?? REGISTRY_FILE_PATH,
      videosRoot: root,
      examplesRoot: opts.examplesRoot ?? DEFAULT_EXAMPLES_ROOT,
    });
  }

  return { dir, metaPath, compositionPath, id, collection, slug };
}
